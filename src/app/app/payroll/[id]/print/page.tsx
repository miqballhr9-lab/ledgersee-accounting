import { and, desc, eq } from "drizzle-orm";
import { notFound } from "next/navigation";

import { db } from "@/db";
import { bookkeepingRecord } from "@/db/schema";
import InvoicePrintButton from "@/components/bookkeeping/InvoicePrintButton";
import { requireUser } from "@/lib/auth";

interface PayrollSlipPageProps {
  params: Promise<{ id: string }>;
}

function amount(value: string | undefined) {
  return new Intl.NumberFormat("en-PK", { style: "currency", currency: "PKR", minimumFractionDigits: 2 }).format(Number(value || 0));
}

export default async function PayrollSlipPage({ params }: PayrollSlipPageProps) {
  const me = await requireUser();
  const { id } = await params;
  const [records, settings] = await Promise.all([
    db
      .select()
      .from(bookkeepingRecord)
      .where(and(eq(bookkeepingRecord.id, id), eq(bookkeepingRecord.userId, me.id), eq(bookkeepingRecord.kind, "payroll")))
      .limit(1),
    db
      .select()
      .from(bookkeepingRecord)
      .where(and(eq(bookkeepingRecord.userId, me.id), eq(bookkeepingRecord.kind, "settings")))
      .orderBy(desc(bookkeepingRecord.updatedAt))
      .limit(1),
  ]);
  if (!records[0]) notFound();

  const employee = records[0].data;
  const companyName = settings[0]?.data.companyName || me.name;
  const otherDeductions = Math.max(0, Number(employee.totalDeductions || 0) - Number(employee.taxDeduction || 0));
  const rows = [
    ["Base salary", amount(employee.baseSalary)],
    ["Increment", amount(employee.increment)],
    ["Salary after increment", amount(employee.afterIncrement)],
    ["Attendance-adjusted salary", amount(employee.proratedSalary)],
    ["Incentive", amount(employee.incentive)],
    ["Overtime allowance", amount(employee.overtimeAllowance)],
    ["Gym allowance", amount(employee.gymAllowance)],
    ["Medical allowance", amount(employee.medicalAllowance)],
    ["Other allowance", amount(employee.otherAllowance)],
    ["Gross salary", amount(employee.grossSalary)],
    ["Income tax", amount(employee.taxDeduction)],
    ["Advance deduction", amount(employee.advanceDeduction)],
    ["Loan deduction", amount(employee.loanDeduction)],
    ["Fine", amount(employee.fineDeduction)],
    ["Adjustment", amount(employee.adjustment)],
    ["Payment account", employee.paymentAccountName ? `${employee.paymentMethod || "Account"} · ${employee.paymentAccountName}` : "Not set"],
    ["Final payable salary", amount(employee.payableSalary)],
  ];

  return (
    <main className="min-h-dvh bg-background px-4 py-8 print:bg-white print:p-0">
      <div className="mx-auto mb-4 flex max-w-3xl justify-end print:hidden"><InvoicePrintButton /></div>
      <article className="mx-auto max-w-3xl border border-border bg-card p-6 text-card-foreground shadow-sm print:max-w-none print:border-0 print:p-8 print:shadow-none sm:p-10">
        <header className="flex flex-wrap items-start justify-between gap-4 border-b border-border pb-6">
          <div>
            <p className="text-sm font-semibold text-primary">{companyName}</p>
            <h1 className="mt-2 text-2xl font-semibold tracking-tight">Salary slip</h1>
            <p className="mt-1 text-sm text-muted-foreground">Pay period: {employee.month || "—"}</p>
            {employee.reference ? <p className="text-sm text-muted-foreground">Ref no.: {employee.reference}</p> : null}
          </div>
          <div className="text-right text-sm">
            <p className="font-semibold">{employee.employeeName || "Employee"}</p>
            <p className="text-muted-foreground">{employee.designation || "—"}</p>
            <p className="mt-1 text-muted-foreground">ID: {employee.employeeId || "—"}</p>
          </div>
        </header>
        <section className="grid gap-3 border-b border-border py-5 text-sm sm:grid-cols-3">
          <p><span className="text-muted-foreground">CNIC</span><br />{employee.cnic || "—"}</p>
          <p><span className="text-muted-foreground">Joining date</span><br />{employee.joiningDate || "—"}</p>
          <p><span className="text-muted-foreground">Attendance</span><br />{employee.workedDays || "0"} / {employee.workingDays || "0"} days</p>
        </section>
        <table className="w-full border-collapse text-sm">
          <tbody>
            {rows.map(([label, value]) => (
              <tr key={label} className={label === "Final payable salary" ? "border-t-2 border-primary font-semibold" : "border-b border-border"}>
                <th className="py-3 text-left font-medium">{label}</th>
                <td className="py-3 text-right tabular-nums">{value}</td>
              </tr>
            ))}
          </tbody>
        </table>
        {employee.description ? <p className="mt-6 border-t border-border pt-4 text-sm"><span className="font-medium">Description:</span> {employee.description}</p> : null}
        <p className="mt-8 text-center text-xs text-muted-foreground">Generated by MIKLEDGER</p>
      </article>
    </main>
  );
}
